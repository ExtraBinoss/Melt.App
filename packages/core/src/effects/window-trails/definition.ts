const number = (
  key: string,
  value: number,
  min: number,
  max: number,
  step = 0.01,
  unit = "",
): NumberEffectParameter => ({
  kind: "number",
  scope: "settings",
  key,
  default: value,
  min,
  max,
  step,
  unit,
  displayScale: 1,
  labelKey: `window-trailsFx:parameter.${key}`,
});
const choice = (key: string, value: string, options: string[]): EffectParameter => ({
  kind: "select",
  scope: "settings",
  key,
  default: value,
  labelKey: `window-trailsFx:parameter.${key}`,
  options: options.map((value) => ({ value, labelKey: `window-trailsFx:choice.${value}` })),
});
