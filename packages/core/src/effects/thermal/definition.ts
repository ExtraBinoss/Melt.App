import { AMOUNT, defineEffect, type EffectParameter } from "../definition";
const number = (
  key: string,
  value: number,
  min: number,
  max: number,
  step = 0.01,
  unit = "",
): EffectParameter => ({
  kind: "number",
  scope: "settings",
  key,
  default: value,
  labelKey: "materialFx:parameter." + key,
  min,
  max,
  step,
  displayScale: 1,
  unit,
});
const choice = (key: string, value: string, options: readonly string[]): EffectParameter => ({
  kind: "select",
  scope: "settings",
  key,
  default: value,
  labelKey: "materialFx:parameter." + key,
  options: options.map((value) => ({ value, labelKey: "materialFx:choice." + value })),
});
export const THERMAL_DEFINITION = defineEffect(
  "thermal",
  { time: 0 },
  [
    { ...AMOUNT, labelKey: "materialFx:parameter.amount" },
    choice("palette", "iron", ["iron", "rainbow", "ice", "mono"]),
    choice("reverse", "normal", ["normal", "reverse"]),
    number("low", 0, 0, 1),
    number("high", 1, 0, 1),
    number("gain", 1, 0.1, 4),
    number("gamma", 1, 0.1, 4),
    number("saturation", 1, 0, 2),
    number("posterize", 0, 0, 1),
    number("bands", 16, 2, 256, 1),
    number("edges", 0, 0, 2),
    number("grain", 0, 0, 0.5),
    number("scanlines", 0, 0, 1),
    number("speed", 0, 0, 10),
    {
      kind: "number",
      key: "time",
      labelKey: "materialFx:parameter.time",
      min: 0,
      max: 86400,
      step: 0.01,
      displayScale: 1,
      unit: "s",
    },
  ],
  "effect",
  "preserve",
  { identityAtZero: true },
);
